str Content_StringReplaceAll(const char* sText, const char* sNeedle, const char* sValue)
{
	xbuffer_struct tBuf;
	const char* p;
	const char* sCursor;
	size_t iNeedleLen;
	char chZero = 0;

	if ( sText == NULL ) {
		return NULL;
	}
	if ( (sNeedle == NULL) || (sNeedle[0] == '\0') ) {
		return xrtCopyStr((str)sText, 0);
	}
	if ( sValue == NULL ) {
		sValue = "";
	}

	iNeedleLen = strlen(sNeedle);
	xrtBufferInit(&tBuf, (uint32)(strlen(sText) + strlen(sValue) + 32));
	sCursor = sText;
	while ( (p = strstr(sCursor, sNeedle)) != NULL ) {
		if ( p > sCursor ) {
			xrtBufferAppend(&tBuf, (ptr)sCursor, (uint32)(p - sCursor), XBUF_BINARY);
		}
		xrtBufferAppend(&tBuf, (ptr)sValue, (uint32)strlen(sValue), XBUF_BINARY);
		sCursor = p + iNeedleLen;
	}
	xrtBufferAppend(&tBuf, (ptr)sCursor, (uint32)strlen(sCursor), XBUF_BINARY);
	xrtBufferAppend(&tBuf, &chZero, 1, XBUF_BINARY);
	return (str)tBuf.Buffer;
}

str Content_TemplateSet(str sTemplate, const char* sNeedle, const char* sValue)
{
	str sNext = Content_StringReplaceAll(sTemplate, sNeedle, sValue);
	if ( sTemplate ) {
		xrtFree(sTemplate);
	}
	return sNext;
}

