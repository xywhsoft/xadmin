str Content_SanitizeSqlIdent(const char* sText, const char* sFallback)
{
	xbuffer_struct tBuf;
	char chZero = 0;
	bool bHasChar = FALSE;

	xrtBufferInit(&tBuf, 64);
	if ( sText ) {
		for ( const char* p = sText; *p; p++ ) {
			char c = *p;
			if ( ((c >= 'a') && (c <= 'z')) || ((c >= 'A') && (c <= 'Z')) || ((c >= '0') && (c <= '9')) || (c == '_') ) {
				xrtBufferAppend(&tBuf, &c, 1, XBUF_BINARY);
				bHasChar = TRUE;
			}
		}
	}
	if ( !bHasChar ) {
		const char* sDefault = Content_TextOr(sFallback, "content_record");
		xrtBufferAppend(&tBuf, (ptr)sDefault, (uint32)strlen(sDefault), XBUF_BINARY);
	}
	xrtBufferAppend(&tBuf, &chZero, 1, XBUF_BINARY);
	return (str)tBuf.Buffer;
}

