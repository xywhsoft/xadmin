str Content_StripUtf8BomTake(str sText, uint32* pSize)
{
	size_t iLen;
	str sClean;

	if ( sText == NULL ) {
		return NULL;
	}
	iLen = pSize ? (size_t)(*pSize) : strlen(sText);
	if ( iLen < 3 ) {
		return sText;
	}
	if ( ((unsigned char)sText[0] != 0xEF) || ((unsigned char)sText[1] != 0xBB) || ((unsigned char)sText[2] != 0xBF) ) {
		return sText;
	}

	sClean = xrtCopyStr(sText + 3, iLen - 3);
	xrtFree(sText);
	if ( pSize ) {
		*pSize = sClean ? (uint32)(iLen - 3) : 0;
	}
	return sClean;
}

